# Food Waste: The Climate Impact on Your Plate

One-third of all food produced globally is wasted. This isn't just a moral issue in a world where 800 million face hunger—it's an enormous environmental crisis with massive climate implications.

## The Scale of Waste

**1.3 Billion Tons Annually**: One-third of all food produced for human consumption is wasted—enough to feed 2 billion people.

**Per Person**: In industrialized countries, consumers waste 95-115 kg per year. In developing countries, most waste occurs in production and distribution.

**Economic Loss**: Food waste costs the global economy approximately 1 trillion annually.

## If Food Waste Were a Country

Food waste would be the world's third-largest greenhouse gas emitter, after the US and China. It produces about 8-10% of global emissions—approximately 4.4 gigatons of CO2 equivalent annually.

## Why Food Waste Produces Emissions

**Production Emissions**: Growing food requires:
- Clearing land (releasing stored carbon)
- Fertilizers (energy-intensive to produce)
- Pesticides and herbicides
- Fuel for machinery
- Water and energy for irrigation
- Feed for livestock (with associated emissions)

**Processing and Transportation**: Energy for processing, packaging (often plastic), refrigeration, and transport across thousands of miles.

**Decomposition**: In landfills, food decomposes without oxygen, producing methane—a greenhouse gas 25-28 times more potent than CO2 over 100 years.

**Opportunity Cost**: Resources used for wasted food could have been used more productively.

## Where Waste Happens

**In Developing Countries (40% at production/distribution)**:
- Inadequate storage
- Poor infrastructure
- Lack of refrigeration
- Losses during transport

**In Developed Countries (40% at retail/consumer)**:
- Overstocking by retailers
- Strict cosmetic standards (rejecting "ugly" produce)
- Confusion over date labels
- Large portion sizes
- Poor meal planning

**Throughout the Chain**:
- Farms: Imperfect produce rejected, unharvested crops
- Processing: Trimming, quality control rejections
- Distribution: Transportation losses
- Retail: Overstocking, display damage
- Food service: Plate waste, overproduction
- Homes: Spoilage, over-preparation, plate waste

