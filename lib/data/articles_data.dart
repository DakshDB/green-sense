# Water Scarcity: The Coming Global Crisis

Water is essential for life, yet it's becoming increasingly scarce. Despite covering 71% of Earth's surface, less than 1% of water is accessible freshwater for human use. Understanding and addressing water scarcity is critical for our future.

## The Global Water Crisis

**2 Billion People Lack Safe Drinking Water**: That's one in four people globally without reliable access to clean water.

**3.6 Billion Face Water Scarcity**: At least one month per year, about half the global population experiences severe water scarcity.

**Growing Demand**: Global water use has increased sixfold in the past 100 years and continues growing at 1% annually.

**Unequal Distribution**: Water resources are unevenly distributed geographically and temporally, with some regions chronically water-stressed while others have abundance.

## Why Water is Becoming Scarce

**Population Growth**: More people need more water for drinking, sanitation, and food production.

**Climate Change**:
- Altered precipitation patterns (more droughts, intense rainfall)
- Glacier melt affecting water availability
- Increased evaporation
- Sea-level rise contaminating coastal freshwater

**Agriculture Demands**: 70% of global freshwater withdrawals go to agriculture, primarily irrigation.

**Groundwater Depletion**: Many aquifers are being pumped faster than they recharge. The Ogallala Aquifer (US) and aquifers in India and China are critically depleted.

**Pollution**: Contamination makes available water unusable. Industrial waste, agricultural runoff, and inadequate sanitation pollute water sources.

**Inefficient Use**: Leaky infrastructure, wasteful practices, and inefficient irrigation lose vast amounts of water.

## Impacts

**Health**: Waterborne diseases kill thousands daily. Lack of clean water and sanitation causes illness, affecting especially children.

**Food Security**: Water scarcity limits food production. It takes 1,800 gallons of water to produce one pound of beef.

**Economic**: Water scarcity costs global economy billions through reduced productivity, health impacts, and conflicts over resources.

**Conflict**: Water stress contributes to instability and conflict. "Water wars" are a real concern.

**Environmental**: Rivers run dry (Colorado River rarely reaches the sea), wetlands disappear, ecosystems collapse.

**Gender**: Women and girls often bear the burden of water collection, spending hours daily walking to water sources, limiting education and opportunities.

## Agriculture: The Biggest Water User

**Irrigation**: Often inefficient, with much water lost to evaporation. Flood irrigation is particularly wasteful.

**Meat Production**: Producing animal products requires vastly more water than plant foods. Beef requires 15,000 liters per kilogram; vegetables need 300 liters.

**Virtual Water**: Water embedded in products. A cotton t-shirt requires 2,700 liters; a cup of coffee, 140 liters.

