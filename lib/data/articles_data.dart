Water scarcity isn't inevitable. With better management, efficiency, conservation, and technology, we can ensure water security. But action is needed now.

Access to clean water is a human right. Every person deserves safe drinking water and sanitation. As populations grow and climate changes, the challenge intensifies, but so must our response.

