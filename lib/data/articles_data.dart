# Climate Change 101: Understanding Our Warming Planet

Climate change is one of the defining challenges of our time. Understanding what it is, why it's happening, and what we can do about it is crucial for everyone on our planet.

## What is Climate Change?

Climate change refers to long-term shifts in global temperatures and weather patterns. While climate naturally varies, scientific evidence shows that current warming trends are extremely likely (greater than 95% probability) to be the result of human activity since the mid-20th century.

The primary driver is the greenhouse effect. Certain gases in Earth's atmosphere trap heat, much like glass in a greenhouse. Carbon dioxide (CO2), methane, and other greenhouse gases absorb heat radiating from Earth's surface and re-emit it, warming the planet.

## The Science is Clear

Our planet has warmed by approximately 1.1°C (2°F) since pre-industrial times. This might sound small, but it's causing significant changes:

**Temperature Rise**: The last decade (2011-2020) was the warmest on record. Nineteen of the warmest years have occurred since 2000.

**CO2 Levels**: Atmospheric CO2 now exceeds 420 parts per million (ppm), higher than at any time in at least 800,000 years. Before the Industrial Revolution, CO2 levels were around 280 ppm.

**Scientific Consensus**: 97% of actively publishing climate scientists agree that climate-warming trends over the past century are extremely likely due to human activities.

## What's Causing It?

Human activities are the primary driver of recent climate change:

**Burning Fossil Fuels**: Coal, oil, and gas for electricity, heat, and transportation release vast amounts of CO2. This accounts for about 75% of global greenhouse gas emissions.

**Deforestation**: Trees absorb CO2, so cutting them down removes this natural carbon sink while releasing stored carbon. About 10 billion trees are cut down annually.

**Agriculture**: Livestock, especially cattle, produce methane during digestion. Rice paddies and fertilizers also release greenhouse gases.

**Industrial Processes**: Manufacturing cement, steel, and chemicals releases significant emissions.

## The Impacts We're Seeing

Climate change affects every aspect of our environment:

**Rising Temperatures**: Heatwaves are becoming more frequent and intense. 2023 was the hottest year on record globally.

**Melting Ice**: Arctic sea ice is declining by about 13% per decade. Glaciers worldwide are retreating. The Greenland and Antarctic ice sheets are losing mass at accelerating rates.

**Rising Seas**: Sea levels have risen 8-9 inches (21-24 centimeters) since 1880. The rate of rise has doubled since 2006. By 2100, seas could rise by 1-4 feet or more, threatening coastal communities worldwide.

**Extreme Weather**: Hurricanes are becoming more intense. Droughts are lasting longer. Heavy rainfall events are more frequent, causing flooding.

**Ocean Changes**: Oceans absorb about 30% of human-generated CO2, making them more acidic. This threatens coral reefs and shellfish. Ocean temperatures are also rising, disrupting marine ecosystems.

**Ecosystem Disruption**: Many species are moving toward the poles or to higher elevations to find suitable habitats. Some are facing extinction. Spring arrives earlier, affecting plant flowering and animal migration patterns.

## The Human Cost

Climate change isn't just an environmental issue—it's a humanitarian crisis:

**Health Impacts**: Heat-related illnesses are increasing. Air pollution from fossil fuels causes 7 million premature deaths annually. Changing disease patterns, including the spread of tropical diseases to new areas.

**Food Security**: Changing rainfall patterns and increased droughts threaten crop yields. Fish populations are shifting due to warming oceans.

**Water Scarcity**: Changing precipitation patterns and melting glaciers affect water availability for millions.

**Displacement**: The UN predicts 200 million climate refugees by 2050 due to rising seas, droughts, and extreme weather.

